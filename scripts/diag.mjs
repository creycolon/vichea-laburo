const list = await (await fetch('http://127.0.0.1:9380/json/list')).json();
const t = list.find(x => x.type === 'page');
const ws = new WebSocket(t.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
const call = (m, p = {}, ms = 8000) => new Promise(res => { const i = ++id; pend.set(i, res); ws.send(JSON.stringify({ id: i, method: m, params: p })); setTimeout(()=>{if(pend.has(i)){pend.delete(i);res(null);}}, ms); });
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result ?? m.error); pend.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const v = async (e) => (await call('Runtime.evaluate', { expression: e, returnByValue: true }))?.result?.value;
console.log('url:', await v('location.href'));
console.log('body start:', (await v('document.body.innerText.slice(0,200)') || '').replace(/\n/g,' | '));
console.log('rows:', await v("document.querySelectorAll('#rows tr').length"));
console.log('radar data?:', await v('typeof window.__RADAR__'));
console.log('vichea?:', await v('typeof window.__vichea'));
ws.close(); process.exit(0);
